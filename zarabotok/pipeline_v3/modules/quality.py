"""Стандарт качества генераций, портированный из методологии DeepSeek Harness
(dsh-trim-cot-leakage, dsh-prose-standard, dsh-find-simplifications).

Цель: агенты и писатели не выдают «тупые/шаблонные» ответы — только готовый,
конкретный результат без рассуждений, вступлений и воды.
"""

QUALITY_STANDARD = (
    "СТАНДАРТ КАЧЕСТВА (обязателен):\n"
    "- Давай ТОЛЬКО готовый результат заказа. Не пиши рассуждения, не объясняй метод, "
    "не давай вступлений («Как ИИ…», «Я проанализирую…», «Сначала я…»).\n"
    "- Будь конкретен: действие, условие, результат, ответственность. Без канцелярита, воды и повторов.\n"
    "- Формулируй факты в настоящем времени как свершившийся результат, а не как процесс выполнения.\n"
    "- Код — рабочий, с кратким комментарием к неочевидному. Текст — готовый материал целиком.\n"
    "- Объём оправдан результатом, а не минимизацией; не выкидывай важные факты."
)

# Стартеры строк-паразитов (нижний регистр, после strip): целая КОРОТКАЯ такая
# строка удаляется целиком; длинные строки сохраняются (снимается только префикс).
_FILLER_LINE_STARTS = (
    "привет", "здравствуйте", "добрый день", "доброго времени", "конечно",
    "спасибо", "надеюсь", "я помогу", "если у вас есть вопросы", "если нужно",
    "напишите", "с уважением", "удачи", "вот мой", "ниже представлен",
    "как искусственный интеллект", "в качестве ии", "я — ии", "я ai",
)

# Фразы-паразиты, которые снимаются в начале/конце (префикс или суффикс, цикл).
_FILLER_PHRASES = (
    "привет! ", "здравствуйте! ", "добрый день! ", "доброго времени! ",
    "конечно! ", "конечно, ", "спасибо за задание. ", "спасибо! ", "спасибо за ",
    "надеюсь, это было полезно. ", "если у вас остались вопросы, пишите. ",
    "если нужно что-то поправить, пишите. ", "с уважением, (ваше имя). ",
    "с уважением. ", "я помогу вам. ", "я помогу ", "как ии, ", "как ai, ",
    "вот мой ответ: ", "вот ответ: ", "ниже представлен ", "как искусственный интеллект, ",
    "в качестве ии, ", "я — ии. ",
)


def _pure_filler(low: str) -> bool:
    return any(low.startswith(p) for p in _FILLER_LINE_STARTS) and len(low.split()) <= 8


def inject(system_prompt: str) -> str:
    """Добавить стандарт качества к системному промпту (без дублей)."""
    if not system_prompt:
        return QUALITY_STANDARD
    if "СТАНДАРТ КАЧЕСТВА" in system_prompt:
        return system_prompt
    return system_prompt.rstrip() + "\n\n" + QUALITY_STANDARD


def clean_output(text: str) -> str:
    """Убрать шаблонные ИИ-вступления/прощания и рассуждения-в-начале.

    Снимает префикс/суффикс-фразы по циклу, а целые строки удаляет только если
    они ЦЕЛИКОМ паразитные (короткие) — чтобы не потерять полезный контент."""
    if not text:
        return ""
    res = text.strip()
    # целый текст: снимаем обёртки-фразы в начале/конце (пока что-то меняется)
    changed = True
    while changed:
        changed = False
        low = res.lower()
        for ph in _FILLER_PHRASES:
            if low.startswith(ph):
                res = res[len(ph):].strip()
                changed = True
                break
            suf = ph.rstrip()
            if suf and low.endswith(suf):
                res = res[: -len(suf)].strip()
                changed = True
                break
    # построчно: снять префикс-паразит внутри строки, дропнуть строки-паразиты целиком
    out = []
    for ln in res.splitlines():
        s = ln.strip()
        if not s:
            out.append(ln)
            continue
        low_s = s.lower()
        for ph in _FILLER_PHRASES:
            if low_s.startswith(ph):
                s = s[len(ph):].strip()
                low_s = s.lower()
        if _pure_filler(low_s):
            continue
        out.append(s)
    return "\n".join(out).strip()
